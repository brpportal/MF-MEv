-- 5. Evidence Exports Metadata (Only Admin Panel can decrypt & inspect)
CREATE TABLE IF NOT EXISTS public.evidence_exports (
    export_id TEXT PRIMARY KEY,
    batch_id TEXT NOT NULL,
    file_name TEXT NOT NULL,
    manifest_sha256 TEXT NOT NULL,
    archive_sha256 TEXT NOT NULL,
    file_size_bytes BIGINT NOT NULL,
    link_count INTEGER NOT NULL,
    screenshot_count INTEGER NOT NULL,
    created_by_user TEXT,
    encryption_algorithm TEXT DEFAULT 'AES-256',
    admin_manageable_only BOOLEAN DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 6. Evidence Batches Metadata
CREATE TABLE IF NOT EXISTS public.evidence_batches (
    operation_id TEXT PRIMARY KEY,
    batch_id TEXT NOT NULL,
    name TEXT,
    total_links INTEGER DEFAULT 0,
    synced_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 7. Evidence Screenshots Metadata
CREATE TABLE IF NOT EXISTS public.evidence_screenshots (
    operation_id TEXT PRIMARY KEY,
    screenshot_id TEXT,
    link_id TEXT,
    batch_id TEXT,
    url TEXT,
    sha256 TEXT,
    synced_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 8. Enable Row Level Security (RLS) & Allow Access for Authenticated Users / Anon API
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.app_registrations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pairing_codes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.config ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.evidence_exports ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.evidence_batches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.evidence_screenshots ENABLE ROW LEVEL SECURITY;

-- Permissive policies for authorized app API calls
CREATE POLICY "Allow public read/write app_registrations" ON public.app_registrations FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read/write pairing_codes" ON public.pairing_codes FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read config" ON public.config FOR SELECT USING (true);
CREATE POLICY "Allow public read/write config" ON public.config FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read/write evidence_exports" ON public.evidence_exports FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read/write evidence_batches" ON public.evidence_batches FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read/write evidence_screenshots" ON public.evidence_screenshots FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow user read/write profile" ON public.profiles FOR ALL USING (true) WITH CHECK (true);
