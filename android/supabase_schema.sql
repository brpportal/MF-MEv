-- Enable UUID extension if not already enabled
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. Profiles Table (Extends Supabase auth.users)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
    email TEXT,
    display_name TEXT,
    team_name TEXT DEFAULT 'Evidence Team Alpha',
    role TEXT DEFAULT 'Evidence Specialist',
    is_authorized BOOLEAN DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. App Registrations & Device Activation (Real-time linking with Android App)
CREATE TABLE IF NOT EXISTS public.app_registrations (
    user_id TEXT PRIMARY KEY,
    status TEXT DEFAULT 'NOT_LINKED', -- 'ACTIVATED', 'LINKED', 'WAITING_CONFIRMATION', 'ACCESS_REVOKED', 'NOT_LINKED'
    team_id TEXT DEFAULT 'Evidence Team Alpha',
    pairing_code TEXT,
    device_info TEXT,
    linked_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. 6-Digit Pairing Codes (Generated by Admin Panel on website)
CREATE TABLE IF NOT EXISTS public.pairing_codes (
    code TEXT PRIMARY KEY CHECK (length(code) = 6),
    team_id TEXT DEFAULT 'Evidence Team Alpha',
    used_by TEXT,
    is_used BOOLEAN DEFAULT false,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    consumed_at TIMESTAMP WITH TIME ZONE
);

-- 4. Central Config (Admin-Managed Archive Password & Settings)
CREATE TABLE IF NOT EXISTS public.config (
    key TEXT PRIMARY KEY,
    value JSONB NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

